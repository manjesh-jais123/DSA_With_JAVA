package Basic;

public class asciiValue {
    public static void main(String[] args) {
        char man = 'M';
        int m = man;
        System.out.println(m);

        char woman = 'a';
        int w = woman;
        System.out.println(w);

        char ch = 'c';
        System.out.println(ch*1);

        char cha = 'c';
        System.out.println(cha*cha);

        int x = 43;
        char ch1 = (char)x;
        System.out.println(ch1);


        int y = 105;
        char ch12 = (char)y;
        System.out.println(ch12);
    }
}
